                'text' => 'holds full directional strength (Digbala) in this position, which amplifies everything it signifies',
                'conditions' => null,
            ],
            [
                'condition_type' => 'digbala',
                'condition_key' => 'strong',
                'section' => 'modifier',
                'polarity' => 1,
                'weight' => 55,
                'text' => 'is directionally well placed, lending steadiness to its results',
                'conditions' => null,
            ],
            [
                'condition_type' => 'digbala',
                'condition_key' => 'weak',
                'section' => 'modifier',
                'polarity' => -1,
                'weight' => 55,
                'text' => 'lacks directional strength here, so its results require deliberate effort to materialise',
                'conditions' => null,
            ],
            [
                'condition_type' => 'digbala',
                'condition_key' => 'powerless',
                'section' => 'modifier',
                'polarity' => -2,
                'weight' => 70,
                'text' => 'is directionally powerless in this house, which markedly undercuts its capacity to deliver',
                'conditions' => null,
            ],
        ];
    }
}
